// Monday → Project Tools live sync webhook.
//
// Subscribed events (per board, via Monday automations OR native webhooks):
//   - create_pulse                 : new item appeared on the board
//   - change_status_column_value   : status column flipped (any value)
//
// Handlers:
//   - Pre-sales create_pulse  → assign Project ID, upsert Supabase row
//                               (phase = 'Pre-Sales', status from Monday)
//   - Post-sales create_pulse → look up row by project_code (Monday auto-copies
//                               it on the pre-sales→post-sales duplication),
//                               flip phase to 'Post-Sales' and link the new
//                               post-sales item id. Generates a code if
//                               somehow missing.
//   - Status change           → look up row by which board fired and update
//                               status only.
//
// Compatible with both native API webhook payloads AND payloads generated by
// Monday's "When X happens, send a webhook" automation recipes — the two
// formats differ in subtle ways and we sniff for whichever fields are present.
//
// The Monday handshake (`{ challenge: "..." }`) is echoed back unchanged so
// subscription verification keeps working.

import { serve } from 'https://deno.land/std@0.177.0/http/server.ts';
import { createClient, SupabaseClient } from 'https://esm.sh/@supabase/supabase-js@2';

const PRESALES_BOARD_ID  = 3477536693;
const POSTSALES_BOARD_ID = 3523133226;
const STATUS_COLUMN_ID   = 'status9';
const PRESALES_PROJECT_ID_COL  = 'text_mm2rcnav';
const POSTSALES_PROJECT_ID_COL = 'text_mm2rsn';

const MONDAY_API = 'https://api.monday.com/v2';

// ── Helpers ─────────────────────────────────────────────────────────────────

function normalizeStatus(raw: string | null | undefined): string {
  if (!raw) return 'Not Started';
  const s = String(raw).trim();
  if (!s) return 'Not Started';
  if (s.toLowerCase() === 'on hold') return 'On Hold';
  return s;
}

async function mondayQuery(token: string, query: string): Promise<any> {
  const res = await fetch(MONDAY_API, {
    method: 'POST',
    headers: {
      'Authorization': token,
      'Content-Type': 'application/json',
      'API-Version': '2024-10',
    },
    body: JSON.stringify({ query }),
  });
  const json = await res.json();
  if (json.errors) {
    throw new Error(`Monday GraphQL: ${JSON.stringify(json.errors)}`);
  }
  return json;
}

// Pull a single item's name + Project ID + status from Monday. Used by
// create_pulse handlers since the webhook payload doesn't always include
// the column values we need (especially for automation-style payloads).
async function fetchItem(
  token: string,
  itemId: number,
  projectIdColumn: string,
): Promise<{ name: string; projectCode: string; status: string } | null> {
  const query = `query { items(ids: [${itemId}]) {
    id name
    column_values(ids: ["${projectIdColumn}", "${STATUS_COLUMN_ID}"]) { id text }
  } }`;
  const res = await mondayQuery(token, query);
  const item = res.data?.items?.[0];
  if (!item) return null;
  const cols: Array<{ id: string; text: string | null }> = item.column_values ?? [];
  const code = cols.find((c) => c.id === projectIdColumn)?.text?.trim() ?? '';
  const status = cols.find((c) => c.id === STATUS_COLUMN_ID)?.text?.trim() ?? '';
  return { name: String(item.name ?? ''), projectCode: code, status };
}

async function writeProjectCode(
  token: string,
  boardId: number,
  itemId: number,
  columnId: string,
  code: string,
): Promise<void> {
  const query = `mutation {
    change_simple_column_value(
      board_id: ${boardId},
      item_id: ${itemId},
      column_id: "${columnId}",
      value: "${code}"
    ) { id }
  }`;
  await mondayQuery(token, query);
}

async function generateProjectCode(supabase: SupabaseClient): Promise<string | null> {
  const { data, error } = await supabase.rpc('generate_project_code');
  if (error || !data) return null;
  return String(data);
}

// ── Event-shape sniffers ────────────────────────────────────────────────────
// Native API webhook payloads use `event.type` (e.g. "create_pulse",
// "change_column_value", "update_column_value"). Automation-generated
// webhooks may omit `type` or use slightly different field names. We treat
// presence of certain fields as the canonical signal.

interface ParsedEvent {
  kind: 'create_pulse' | 'status_change' | 'unknown';
  boardId?: number;
  pulseId?: number;
  pulseName?: string;
  newStatusLabel?: string;
  columnId?: string;
}

function parseEvent(body: any): ParsedEvent {
  const ev = body?.event ?? {};
  const type = String(ev.type ?? '').toLowerCase();
  const boardId = Number(ev.boardId ?? ev.board_id ?? NaN);
  const pulseId = Number(ev.pulseId ?? ev.itemId ?? ev.pulse_id ?? ev.item_id ?? NaN);
  const pulseName = ev.pulseName ?? ev.itemName ?? ev.pulse_name ?? undefined;
  const columnId = ev.columnId ?? ev.column_id ?? undefined;

  if (type === 'create_pulse' || (Number.isFinite(pulseId) && pulseName && !columnId && !ev.value)) {
    return { kind: 'create_pulse', boardId, pulseId, pulseName: String(pulseName ?? '') };
  }

  // Status change can arrive as change_column_value, update_column_value, or
  // change_specific_column_value. The discriminator we trust most is the
  // column id matching status9 + a value object containing a label.
  if (columnId === STATUS_COLUMN_ID || type.includes('column_value')) {
    const valueLabel: string | undefined =
      ev?.value?.label?.text ??
      ev?.value?.label ??
      ev?.value?.value ??
      undefined;
    return {
      kind: 'status_change',
      boardId,
      pulseId,
      columnId,
      newStatusLabel: valueLabel ? String(valueLabel) : undefined,
    };
  }

  return { kind: 'unknown', boardId, pulseId };
}

// ── Handlers ────────────────────────────────────────────────────────────────

async function handlePresalesCreate(
  ev: ParsedEvent,
  supabase: SupabaseClient,
  token: string,
): Promise<void> {
  if (!ev.pulseId) return;
  const item = await fetchItem(token, ev.pulseId, PRESALES_PROJECT_ID_COL);
  if (!item) {
    console.warn('[monday-webhook] Pre-sales create_pulse: item not found', ev.pulseId);
    return;
  }

  // Assign code if missing.
  let code = item.projectCode;
  if (!code) {
    const generated = await generateProjectCode(supabase);
    if (!generated) {
      console.error('[monday-webhook] Failed to generate project code for pre-sales item', ev.pulseId);
      return;
    }
    await writeProjectCode(token, PRESALES_BOARD_ID, ev.pulseId, PRESALES_PROJECT_ID_COL, generated);
    code = generated;
  }

  // Upsert Supabase row keyed on project_code.
  const { data: existing } = await supabase
    .from('projects')
    .select('id')
    .eq('project_code', code)
    .maybeSingle();

  const row = {
    name: item.name,
    project_code: code,
    monday_presales_item_id: ev.pulseId,
    phase: 'Pre-Sales' as const,
    status: normalizeStatus(item.status),
  };

  if (existing?.id) {
    await supabase.from('projects').update(row).eq('id', existing.id);
  } else {
    await supabase.from('projects').insert(row);
  }
  console.log('[monday-webhook] Pre-sales create handled', { pulseId: ev.pulseId, code });
}

async function handlePostsalesCreate(
  ev: ParsedEvent,
  supabase: SupabaseClient,
  token: string,
): Promise<void> {
  if (!ev.pulseId) return;
  const item = await fetchItem(token, ev.pulseId, POSTSALES_PROJECT_ID_COL);
  if (!item) {
    console.warn('[monday-webhook] Post-sales create_pulse: item not found', ev.pulseId);
    return;
  }

  // Generate a code only if Monday's duplication automation didn't carry one
  // over (shouldn't happen for the common case, but covers manual creates).
  let code = item.projectCode;
  if (!code) {
    const generated = await generateProjectCode(supabase);
    if (!generated) return;
    await writeProjectCode(token, POSTSALES_BOARD_ID, ev.pulseId, POSTSALES_PROJECT_ID_COL, generated);
    code = generated;
  }

  const { data: existing } = await supabase
    .from('projects')
    .select('id')
    .eq('project_code', code)
    .maybeSingle();

  const row = {
    name: item.name,
    project_code: code,
    monday_postsales_item_id: ev.pulseId,
    phase: 'Post-Sales' as const,
    status: normalizeStatus(item.status),
  };

  if (existing?.id) {
    await supabase.from('projects').update(row).eq('id', existing.id);
  } else {
    await supabase.from('projects').insert(row);
  }
  console.log('[monday-webhook] Post-sales create handled (phase flipped)', { pulseId: ev.pulseId, code });
}

async function handleStatusChange(
  ev: ParsedEvent,
  supabase: SupabaseClient,
  token: string,
): Promise<void> {
  if (!ev.pulseId || !ev.boardId) return;
  const isPresales = ev.boardId === PRESALES_BOARD_ID;
  const isPostsales = ev.boardId === POSTSALES_BOARD_ID;
  if (!isPresales && !isPostsales) return;

  // Prefer the label from the webhook payload; fall back to fetching from
  // Monday if the payload didn't include one (some automation payloads omit
  // the resolved label).
  let label = ev.newStatusLabel;
  if (!label) {
    const item = await fetchItem(
      token,
      ev.pulseId,
      isPresales ? PRESALES_PROJECT_ID_COL : POSTSALES_PROJECT_ID_COL,
    );
    if (!item) return;
    label = item.status;
  }

  const status = normalizeStatus(label);
  const itemIdColumn = isPresales ? 'monday_presales_item_id' : 'monday_postsales_item_id';

  const { data: rows, error } = await supabase
    .from('projects')
    .update({ status })
    .eq(itemIdColumn, ev.pulseId)
    .select('id, project_code');

  if (error) {
    console.error('[monday-webhook] Status update failed', error.message);
    return;
  }
  if (!rows || rows.length === 0) {
    // Project hasn't been linked yet — common during the brief window between
    // an item being created and the create_pulse event being processed.
    // Re-queue by triggering a create handler; that path is idempotent.
    console.warn('[monday-webhook] Status change for unlinked item — running create handler', { pulseId: ev.pulseId, board: isPresales ? 'pre' : 'post' });
    if (isPresales) await handlePresalesCreate(ev, supabase, token);
    else await handlePostsalesCreate(ev, supabase, token);
    return;
  }
  console.log('[monday-webhook] Status synced', { pulseId: ev.pulseId, status, rows: rows.length });
}

// ── Server ──────────────────────────────────────────────────────────────────

serve(async (req) => {
  if (req.method !== 'POST') {
    return new Response('Method not allowed', { status: 405 });
  }

  let body: any;
  try { body = await req.json(); }
  catch { return new Response('Invalid JSON', { status: 400 }); }

  // Monday handshake — must echo the challenge for subscription verification.
  if (body?.challenge) {
    return new Response(JSON.stringify({ challenge: body.challenge }), {
      headers: { 'Content-Type': 'application/json' },
    });
  }

  const ev = parseEvent(body);
  console.log('[monday-webhook] Event', { kind: ev.kind, boardId: ev.boardId, pulseId: ev.pulseId, columnId: ev.columnId, label: ev.newStatusLabel });

  if (ev.kind === 'unknown' || !ev.boardId || !ev.pulseId) {
    return new Response(JSON.stringify({ status: 'ignored', reason: 'unrecognized event shape' }), {
      headers: { 'Content-Type': 'application/json' },
    });
  }

  const mondayToken = Deno.env.get('MONDAY_API_TOKEN');
  if (!mondayToken) {
    console.error('[monday-webhook] MONDAY_API_TOKEN not set');
    return new Response(JSON.stringify({ status: 'error', reason: 'no_monday_token' }), {
      status: 500, headers: { 'Content-Type': 'application/json' },
    });
  }

  const supabaseUrl = Deno.env.get('SUPABASE_URL')!;
  const serviceKey  = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
  const supabase    = createClient(supabaseUrl, serviceKey);

  try {
    if (ev.kind === 'create_pulse') {
      if (ev.boardId === PRESALES_BOARD_ID) {
        await handlePresalesCreate(ev, supabase, mondayToken);
      } else if (ev.boardId === POSTSALES_BOARD_ID) {
        await handlePostsalesCreate(ev, supabase, mondayToken);
      }
    } else if (ev.kind === 'status_change') {
      await handleStatusChange(ev, supabase, mondayToken);
    }
  } catch (err) {
    console.error('[monday-webhook] Handler error:', err);
    return new Response(JSON.stringify({ status: 'error', message: err instanceof Error ? err.message : String(err) }), {
      status: 500, headers: { 'Content-Type': 'application/json' },
    });
  }

  return new Response(JSON.stringify({ status: 'ok', kind: ev.kind }), {
    headers: { 'Content-Type': 'application/json' },
  });
});
